#include <iostream>
#include <memory>
#include <string>

#include <grpcpp/grpcpp.h>

#include "proto/load_balancer.grpc.pb.h"

int main(int argc, char** argv) {
    /*
        Expected command:

        ./client <load_balancer_address>

        Example:

        ./client localhost:5000
    */
    if (argc != 2) {
        std::cerr << "Usage: " << argv[0] << " <load_balancer_address>\n";
        return 1;
    }

    const std::string load_balancer_address = argv[1];

    /*
        Create a gRPC channel to the load balancer.

        The client talks only to the load balancer.
        It does not know how many backend servers exist.
    */
    auto channel = grpc::CreateChannel(
        load_balancer_address,
        grpc::InsecureChannelCredentials()
    );

    /*
        Stub is the client-side object generated by gRPC.

        It gives us a C++ function for calling:

        LoadBalancerService.HandleRequest
    */
    auto stub = loadbalancer::LoadBalancerService::NewStub(channel);

    /*
        Send multiple requests so we can observe round-robin distribution.
    */
    for (int i = 1; i <= 10; ++i) {
        loadbalancer::Request request;
        loadbalancer::Response response;
        grpc::ClientContext context;

        request.set_message("Request " + std::to_string(i));

        grpc::Status status = stub->HandleRequest(
            &context,
            request,
            &response
        );

        if (!status.ok()) {
            std::cerr
                << "Request " << i << " failed: "
                << status.error_message() << "\n";
            continue;
        }

        std::cout
            << "Request " << i
            << " -> " << response.message()
            << " | server_id=" << response.server_id()
            << "\n";
    }

    return 0;
}