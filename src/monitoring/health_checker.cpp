#include "monitoring/health_checker.hpp"

#include <chrono>
#include <iostream>
#include <string>
#include <thread>

#include <google/protobuf/empty.pb.h>

//#include "utils/config.hpp"

/*
    CPU thresholds used by autoscaling.

    If a backend reports CPU > 80%, we add one more server.
    If a backend reports CPU < 20%, we remove that server, but only
    if active_servers is still greater than min_servers.
*/
const double SCALE_UP_CPU_THRESHOLD = 80.0;
const double SCALE_DOWN_CPU_THRESHOLD = 20.0;
int health_checker_sleep_time = 15;

HealthChecker::HealthChecker(const std::string& lb_admin_address) {
    /*
        Create a gRPC channel to the load balancer's AdminService.

        Example:
        lb_admin_address = "127.0.0.1:5000"

        This channel is used to call:
        - ListServers
        - UpdateServerHealth
        - AddServer
        - RemoveServer
        - GetServerConstraints

        The health checker does not directly modify ServerManager.
        It talks to the load balancer through AdminService.
    */
    auto channel = grpc::CreateChannel(
        lb_admin_address,
        grpc::InsecureChannelCredentials()
    );

    /*
        Stub means "client object generated by gRPC".

        admin_stub_ is how HealthChecker sends AdminService requests
        to the load balancer.
    */
    admin_stub_ = admin::AdminService::NewStub(channel);
}

HealthChecker::~HealthChecker() {
    /*
        If HealthChecker is destroyed while the background thread is running,
        stop() makes sure the thread exits cleanly before memory is released.
    */
    stop();
}

void HealthChecker::start() {
    /*
        Prevent starting multiple health checker threads accidentally.
    */
    if (running_) {
        return;
    }

    /*
        running_ is atomic because one thread writes it in start()/stop(),
        and the health checker thread reads it in checkHealth().
    */
    running_ = true;

    /*
        Start a background thread.

        This runs:
        HealthChecker::checkHealth()

        The "this" pointer means the thread runs checkHealth()
        on the current HealthChecker object.
    */
    health_check_thread_ = std::make_unique<std::thread>(
        &HealthChecker::checkHealth,
        this
    );
}

void HealthChecker::stop() {
    /*
        If already stopped, there is nothing to do.
    */
    if (!running_) {
        return;
    }

    /*
        Tell checkHealth() loop to stop.
    */
    running_ = false;

    /*
        Wait for the background thread to finish.

        joinable() means:
        "Is this thread object currently attached to a running thread?"
    */
    if (health_check_thread_ && health_check_thread_->joinable()) {
        health_check_thread_->join();
    }
}

std::vector<admin::ServerInfo> HealthChecker::listAllServers() {
    grpc::ClientContext context;
    google::protobuf::Empty request;
    admin::ListServersResponse response;

    /*
        Call load balancer AdminService.ListServers.

        This returns all backend servers currently known by ServerManager.
    */
    grpc::Status status = admin_stub_->ListServers(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "ListServers RPC failed: "
            << status.error_message()
            << "\n";

        return {};
    }

    /*
        Convert protobuf repeated servers into a normal std::vector.

        response.servers() is generated protobuf API.
        std::vector is easier to use in normal C++ loops.
    */
    std::vector<admin::ServerInfo> servers;

    for (const auto& server : response.servers()) {
        servers.push_back(server);
    }

    return servers;
}

bool HealthChecker::isServerResponding(const std::string& host, int port) {
    /*
        This checks whether the backend gRPC server is reachable.

        Original project used raw socket connect.
        Here we use gRPC connection checking because:
        - backend itself is a gRPC server
        - load balancer talks to backend using gRPC
        - this works on macOS, Linux, and Windows
        - no WinSock/POSIX socket split is needed
    */
    const std::string backend_address =
        host + ":" + std::to_string(port);

    auto channel = grpc::CreateChannel(
        backend_address,
        grpc::InsecureChannelCredentials()
    );

    /*
        Wait at most 2 seconds for the gRPC channel to become connected.

        true:
        backend is reachable

        false:
        backend did not respond before the deadline
    */
    const auto deadline =
        std::chrono::system_clock::now() + std::chrono::seconds(2);

    return channel->WaitForConnected(deadline);
}

bool HealthChecker::getServerMetrics(
    const std::string& host,
    int port,
    double& out_cpu,
    double& out_memory
) {
    /*
        Each backend server also exposes AdminService.GetMetrics.

        HealthChecker calls backend directly for metrics:

        127.0.0.1:6000 -> GetMetrics()
        127.0.0.1:6001 -> GetMetrics()

        The load balancer stores those metric values later using
        UpdateServerHealth.
    */
    const std::string backend_address =
        host + ":" + std::to_string(port);

    auto channel = grpc::CreateChannel(
        backend_address,
        grpc::InsecureChannelCredentials()
    );

    auto backend_admin_stub =
        admin::AdminService::NewStub(channel);

    grpc::ClientContext context;
    google::protobuf::Empty request;
    admin::MetricsResponse response;

    /*
        Do not let metrics RPC hang forever.

        If backend is stuck, this call fails after 2 seconds.
    */
    context.set_deadline(
        std::chrono::system_clock::now() + std::chrono::seconds(2)
    );

    grpc::Status status = backend_admin_stub->GetMetrics(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "GetMetrics RPC failed for "
            << backend_address
            << ": "
            << status.error_message()
            << "\n";

        return false;
    }

    /*
        These are output parameters.

        The caller gives us variables by reference,
        and we fill those variables here.
    */
    out_cpu = response.cpu_usage();
    out_memory = response.memory_usage();

    return true;
}

admin::ServerConstraintsResponse HealthChecker::getServerLimits() {
    grpc::ClientContext context;
    google::protobuf::Empty request;
    admin::ServerConstraintsResponse response;

    /*
        Ask load balancer for scaling limits.

        These values come from ServerManager:
        - min_servers
        - max_servers
        - active_servers
    */
    grpc::Status status = admin_stub_->GetServerConstraints(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "GetServerConstraints RPC failed: "
            << status.error_message()
            << "\n";
    }

    return response;
}

void HealthChecker::addServer() {
    grpc::ClientContext context;
    google::protobuf::Empty request;
    admin::AddServerResponse response;

    /*
        Ask load balancer to add one backend server.

        Internally:
        AdminService::AddServer()
            -> ServerManager::addServer()
            -> starts backend process
            -> stores new Server object
    */
    grpc::Status status = admin_stub_->AddServer(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "AddServer RPC failed: "
            << status.error_message()
            << "\n";

        return;
    }

    std::cout
        << "Created new server with ID "
        << response.id()
        << "\n";
}

void HealthChecker::removeServer(const std::string& server_id) {
    grpc::ClientContext context;
    admin::RemoveServerRequest request;
    google::protobuf::Empty response;

    /*
        Tell load balancer exactly which server should be removed.

        server_id example:
        127.0.0.1:6002
    */
    request.set_id(server_id);

    grpc::Status status = admin_stub_->RemoveServer(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "RemoveServer RPC failed for "
            << server_id
            << ": "
            << status.error_message()
            << "\n";
    }
}

void HealthChecker::updateServerHealth(
    const std::vector<admin::UpdateServerHealthRequest>& updates
) {
    grpc::ClientContext context;
    admin::UpdateServerHealthRequests request;
    google::protobuf::Empty response;

    /*
        Build the repeated protobuf request.

        Each update contains:
        - id
        - isHealthy
        - cpu_usage
        - memory_usage
    */
    for (const auto& update : updates) {
        admin::UpdateServerHealthRequest* item =
            request.add_updates();

        item->set_id(update.id());
        item->set_ishealthy(update.ishealthy());
        item->set_cpu_usage(update.cpu_usage());
        item->set_memory_usage(update.memory_usage());
    }

    /*
        Send all updates to load balancer in one RPC.

        AdminService will call:
        ServerManager::updateServerHealth(...)
    */
    grpc::Status status = admin_stub_->UpdateServerHealth(
        &context,
        request,
        &response
    );

    if (!status.ok()) {
        std::cerr
            << "UpdateServerHealth RPC failed: "
            << status.error_message()
            << "\n";
    }
}

void HealthChecker::handleAutoScaling(
    double cpu,
    const std::string& server_id,
    const admin::ServerConstraintsResponse& constraints
) {
    /*
        Scale up rule:

        If CPU is above 80%, add one backend server.

        We check active_servers < max_servers so we do not exceed
        the maximum allowed server count.
    */
    if (
        cpu > SCALE_UP_CPU_THRESHOLD &&
        constraints.active_servers() < constraints.max_servers()
    ) {
        std::cout
            << "Scaling up because server "
            << server_id
            << " CPU is "
            << cpu
            << "%\n";

        addServer();
        return;
    }

    /*
        Scale down rule:

        If CPU is below 20%, remove that backend server.

        We check active_servers > min_servers so we do not remove
        too many servers.
    */
    if (
        cpu < SCALE_DOWN_CPU_THRESHOLD &&
        constraints.active_servers() > constraints.min_servers()
    ) {
        std::cout
            << "Scaling down server "
            << server_id
            << " because CPU is "
            << cpu
            << "%\n";

        removeServer(server_id);
        return;
    }

    /*
        If neither condition matches, no scaling is needed.
    */
}

void HealthChecker::checkServersOnce() {
    std::cout << "\n=== Health Check Started ===\n";

    /*
        Get current backend list from the load balancer.
    */
    std::vector<admin::ServerInfo> servers = listAllServers();

    /*
        Get min/max/current active server counts.
    */
    admin::ServerConstraintsResponse constraints = getServerLimits();

    /*
        Health updates are collected first and sent together at the end.
    */
    std::vector<admin::UpdateServerHealthRequest> updates;

    for (const auto& server : servers) {
        admin::UpdateServerHealthRequest update;
        update.set_id(server.id());

        /*
            First check if the server is reachable at all.
        */
        const bool responding = isServerResponding(
            server.host(),
            static_cast<int>(server.port())
        );

        /*
            Failure handling:

            If backend is not responding:
            - mark it unhealthy
            - save zero metrics
            - add replacement if max limit allows
            - skip metrics call because server is down
        */
        if (!responding) {
            std::cout
                << "Server "
                << server.id()
                << " is unhealthy. Adding replacement.\n";

            update.set_ishealthy(false);
            update.set_cpu_usage(0.0);
            update.set_memory_usage(0.0);

            if (constraints.active_servers() < constraints.max_servers()) {
                addServer();
            }

            updates.push_back(update);
            continue;
        }

        /*
            Server responded, so mark it healthy.
        */
        update.set_ishealthy(true);

        double cpu = 0.0;
        double memory = 0.0;

        /*
            Ask backend for metrics.

            If this succeeds, we can use CPU for scale up/down.
        */
        if (getServerMetrics(
                server.host(),
                static_cast<int>(server.port()),
                cpu,
                memory
            )) {
            update.set_cpu_usage(cpu);
            update.set_memory_usage(memory);

            std::cout
                << "Server "
                << server.id()
                << " CPU="
                << cpu
                << "% Memory="
                << memory
                << "%\n";

            /*
                Decide whether CPU requires scaling.
            */
            handleAutoScaling(cpu, server.id(), constraints);
        } else {
            /*
                Server was reachable, but metrics RPC failed.

                We keep it healthy because it responded,
                but store zero metrics because we could not read them.
            */
            update.set_cpu_usage(0.0);
            update.set_memory_usage(0.0);
        }

        updates.push_back(update);
    }

    /*
        Push health/metrics changes back into ServerManager.
    */
    updateServerHealth(updates);

    std::cout << "=== Health Check Completed ===\n";
}

void HealthChecker::checkHealth() {
    /*
        Continuous monitoring loop.

        start() launches this function in a background thread.
    */
    while (running_) {
        checkServersOnce();

        /*
            Wait before next cycle.

            health_checker_sleep_time comes from config.cpp.
        */
        std::this_thread::sleep_for(
            std::chrono::seconds(health_checker_sleep_time)
        );
    }
}

int main(int argc, char** argv) {
    /*
        Expected command:

        ./health_checker 127.0.0.1:5000

        Since our load balancer registers AdminService on the same gRPC server
        as LoadBalancerService, this is the load balancer address.
    */
    if (argc != 2) {
        std::cerr
            << "Usage: "
            << argv[0]
            << " <load_balancer_admin_address>\n";

        return 1;
    }

    /*
        Create the health checker client.
    */
    HealthChecker health_checker(argv[1]);

    /*
        Start background monitoring.
    */
    health_checker.start();

    std::cout
        << "Health checker running for "
        << argv[1]
        << "\n";

    std::cout << "Press Enter to stop.\n";

    /*
        Keep process alive until user presses Enter.
    */
    std::string input;
    std::getline(std::cin, input);

    /*
        Stop cleanly before exit.
    */
    health_checker.stop();

    return 0;
}
